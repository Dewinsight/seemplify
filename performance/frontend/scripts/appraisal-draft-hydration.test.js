const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const source = fs.readFileSync(path.join(__dirname, '../lib/appraisal-draft-hydration.ts'), 'utf8');
const loaded = { exports: {} };
new Function('exports', 'module', ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText)(loaded.exports, loaded);
const { hydrateAppraisalDraft: hydrate } = loaded.exports;
const saved = { rating: 3, summary: '', criteria: [{ id: 'a', rating: 3 }] };
const edited = { rating: 4, summary: 'Actual reviewer feedback.', criteria: [{ id: 'a', rating: 4 }] };
const latest = { ...saved, summary: 'Authoritative saved text.' };
test('first matching response initializes the review', () => assert.equal(hydrate('a', 'a', edited, null, saved), saved));
test('same-review refresh updates a pristine form', () => assert.equal(hydrate('a', 'a', structuredClone(saved), { resourceId: 'a', value: saved }, latest), latest));
test('late same-review response preserves unsaved ratings, criteria and narrative', () => assert.equal(hydrate('a', 'a', edited, { resourceId: 'a', value: saved }, latest), edited));
test('switching review initializes its own draft rather than carrying edits forward', () => assert.equal(hydrate('b', 'b', edited, { resourceId: 'a', value: saved }, latest), latest));
test('stale SWR data from another route cannot initialize the new review', () => assert.equal(hydrate('b', 'a', edited, null, saved), edited));
test('successful save baseline permits authoritative server normalization', () => assert.equal(hydrate('a', 'a', edited, { resourceId: 'a', value: edited }, latest), latest));
test('edits made during a save survive its later refresh', () => assert.equal(hydrate('a', 'a', { ...edited, summary: 'Newer typing.' }, { resourceId: 'a', value: edited }, latest).summary, 'Newer typing.'));
